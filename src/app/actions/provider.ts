"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { z } from "zod";
import { checkRole } from "@/lib/auth";
import { formValues, type FormState } from "@/lib/form-state";
import { optionalText } from "@/lib/validation";
import { createClient } from "@/lib/supabase/server";

const MAX_LOGO_BYTES = 2 * 1024 * 1024;
const LOGO_TYPES: Record<string, string> = { "image/png": "png", "image/jpeg": "jpg", "image/webp": "webp" };

const websiteField = z
  .string()
  .trim()
  .max(300)
  .transform((v, ctx) => {
    if (!v) return null;
    const withScheme = /^https?:\/\//i.test(v) ? v : `https://${v}`;
    try {
      const u = new URL(withScheme);
      if (!u.hostname.includes(".")) throw new Error("bad host");
      return u.toString();
    } catch {
      ctx.addIssue({ code: "custom", message: "Enter a valid website, for example example.com." });
      return z.NEVER;
    }
  });

const zipsField = z.string().transform((v, ctx) => {
  const parts = v
    .split(/[\s,;]+/)
    .map((p) => p.trim())
    .filter(Boolean);
  const bad = parts.filter((p) => !/^\d{5}$/.test(p));
  if (bad.length) {
    ctx.addIssue({ code: "custom", message: `These are not 5-digit ZIP codes: ${bad.slice(0, 5).join(", ")}` });
    return z.NEVER;
  }
  const unique = [...new Set(parts)];
  if (unique.length === 0) {
    ctx.addIssue({ code: "custom", message: "Add at least one ZIP code you serve." });
    return z.NEVER;
  }
  if (unique.length > 200) {
    ctx.addIssue({ code: "custom", message: "Add 200 ZIP codes or fewer." });
    return z.NEVER;
  }
  return unique;
});

const profileSchema = z.object({
  business_name: z.string().trim().min(2, "Enter your business name.").max(120),
  tagline: optionalText(160),
  description: optionalText(4000),
  typical_jobs: optionalText(1000),
  phone_public: optionalText(30),
  website: websiteField,
  city: z.string().trim().min(2, "Enter the city you are based in.").max(80),
  state: z.string().trim().min(2, "Enter your state.").max(40),
  service_zips: zipsField,
  years_in_business: z
    .string()
    .trim()
    .transform((v, ctx) => {
      if (!v) return null;
      const n = Number(v);
      if (!Number.isInteger(n) || n < 0 || n > 200) {
        ctx.addIssue({ code: "custom", message: "Enter a whole number of years." });
        return z.NEVER;
      }
      return n;
    }),
  categories: z
    .array(z.uuid())
    .min(1, "Choose at least one service category.")
    .max(8, "Choose up to 8 categories."),
});

/** Create (onboarding) or update the signed-in provider's public profile. */
export async function saveProviderProfile(_prev: FormState, formData: FormData): Promise<FormState> {
  const session = await checkRole("provider");
  if (!session) return { error: "Please log in as a provider." };
  const values = formValues(formData);

  const parsed = profileSchema.safeParse({
    business_name: formData.get("business_name") ?? "",
    tagline: formData.get("tagline") ?? "",
    description: formData.get("description") ?? "",
    typical_jobs: formData.get("typical_jobs") ?? "",
    phone_public: formData.get("phone_public") ?? "",
    website: formData.get("website") ?? "",
    city: formData.get("city") ?? "",
    state: formData.get("state") ?? "",
    service_zips: formData.get("service_zips") ?? "",
    years_in_business: formData.get("years_in_business") ?? "",
    categories: formData.getAll("categories").map(String),
  });
  values.categories = formData.getAll("categories").map(String).join(",");

  if (!parsed.success) {
    return { error: "Please fix the highlighted fields.", fieldErrors: z.flattenError(parsed.error).fieldErrors, values };
  }
  const { categories, ...fields } = parsed.data;

  const logo = formData.get("logo");
  const logoFile = logo instanceof File && logo.size > 0 ? logo : null;
  if (logoFile) {
    if (!LOGO_TYPES[logoFile.type]) return { error: "Logo must be a PNG, JPG or WebP image.", fieldErrors: { logo: ["Use PNG, JPG or WebP."] }, values };
    if (logoFile.size > MAX_LOGO_BYTES) return { error: "Logo must be 2 MB or smaller.", fieldErrors: { logo: ["Max 2 MB."] }, values };
  }

  const supabase = await createClient();
  const { data: existing } = await supabase.from("providers").select("id, logo_url, onboarded_at").eq("profile_id", session.userId).maybeSingle();

  let providerId = existing?.id;
  if (!providerId) {
    const { data: inserted, error } = await supabase
      .from("providers")
      .insert({ profile_id: session.userId, ...fields, onboarded_at: new Date().toISOString() })
      // slug is generated by the database
      .select("id")
      .single();
    if (error || !inserted) {
      console.error("[provider] insert failed:", error?.message);
      return { error: "We could not save your profile. Please try again.", values };
    }
    providerId = inserted.id;
  } else {
    const { error } = await supabase
      .from("providers")
      .update({ ...fields, onboarded_at: existing?.onboarded_at ?? new Date().toISOString() })
      .eq("id", providerId);
    if (error) {
      console.error("[provider] update failed:", error.message);
      return { error: "We could not save your profile. Please try again.", values };
    }
  }

  // Categories: replace the set.
  const { data: current } = await supabase.from("provider_categories").select("category_id").eq("provider_id", providerId);
  const currentIds = new Set((current ?? []).map((c) => c.category_id));
  const wanted = new Set(categories);
  const toRemove = [...currentIds].filter((id) => !wanted.has(id));
  const toAdd = [...wanted].filter((id) => !currentIds.has(id));
  if (toRemove.length) {
    const { error } = await supabase.from("provider_categories").delete().eq("provider_id", providerId).in("category_id", toRemove);
    if (error) console.error("[provider] category delete failed:", error.message);
  }
  if (toAdd.length) {
    const { error } = await supabase.from("provider_categories").insert(toAdd.map((category_id) => ({ provider_id: providerId, category_id })));
    if (error) {
      console.error("[provider] category insert failed:", error.message);
      return { error: "Your profile was saved, but we could not save your categories. Please try again.", values };
    }
  }

  // Logo
  if (logoFile || formData.get("remove_logo") === "on") {
    let logoUrl: string | null = null;
    if (logoFile) {
      const path = `${session.userId}/${Date.now()}.${LOGO_TYPES[logoFile.type]}`;
      const { error: upErr } = await supabase.storage.from("logos").upload(path, logoFile, {
        contentType: logoFile.type,
        cacheControl: "31536000",
        upsert: false,
      });
      if (upErr) {
        console.error("[provider] logo upload failed:", upErr.message);
        return { error: "Your profile was saved, but the logo upload failed. Please try another image.", values };
      }
      logoUrl = supabase.storage.from("logos").getPublicUrl(path).data.publicUrl;
    }
    await supabase.from("providers").update({ logo_url: logoUrl }).eq("id", providerId);
    // Remove the previous file, if it was ours.
    const prefix = "/storage/v1/object/public/logos/";
    if (existing?.logo_url?.includes(prefix)) {
      const oldPath = existing.logo_url.split(prefix)[1];
      if (oldPath?.startsWith(`${session.userId}/`)) await supabase.storage.from("logos").remove([oldPath]);
    }
  }

  revalidatePath("/dashboard", "layout");
  revalidatePath("/providers");

  if (!existing) redirect("/dashboard/link?welcome=1");
  return { ok: true, message: "Your profile is saved." };
}
